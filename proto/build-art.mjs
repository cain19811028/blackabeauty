// Prototype art (2.5D diorama MVP): node proto/build-art.mjs
// Copies the hand-drawn SVG the main site already uses (gown parts, dress form, campus, kapok branch, clouds) and
// the colourway tokens into proto/art.js, so the prototype shows the approved illustrations, not redrawn ones.
// Re-run after the art in index.html changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
const tokens = readFileSync(join(ROOT, 'css/tokens.css'), 'utf8');

function between(source, open, close, from = 0) {
  const a = source.indexOf(open, from);
  if (a < 0) throw new Error(`not found: ${open}`);
  const b = source.indexOf(close, a + open.length);
  if (b < 0) throw new Error(`unterminated: ${open}`);
  return source.slice(a + open.length, b);
}
// Inner markup of the first element whose opening tag starts with `openTag` (attributes may follow).
function innerOf(openTag, closeTag) {
  const a = html.indexOf(openTag);
  if (a < 0) throw new Error(`not found: ${openTag}`);
  const start = html.indexOf('>', a) + 1;
  const end = html.indexOf(closeTag, start);
  return html.slice(start, end).trim();
}

// `.cw-black { --fabric: #2A2D3B; … }` → { 'cw-black': { fabric: '#2A2D3B', … } }
const palettes = {};
for (const [, name, body] of tokens.matchAll(/\.((?:cw|trim|cap|tassel)-[a-z]+)\s*\{([^}]*)\}/g)) {
  palettes[name] = Object.fromEntries([...body.matchAll(/--([a-z-]+):\s*([^;]+);/g)].map(([, k, v]) => [k, v.trim()]));
}
for (const need of ['cw-black', 'cw-crimson', 'trim-silver', 'trim-gold', 'cap-black', 'tassel-silver', 'tassel-gold']) {
  if (!palettes[need]) throw new Error(`palette missing in tokens.css: ${need}`);
}

const art = {
  // every symbol, gradient and filter the illustrations share
  defs: between(html, '<defs>', '</defs>', html.indexOf('<svg xmlns="http://www.w3.org/2000/svg" width="0"')).trim(),
  palettes,
  campus: innerOf('<svg class="campus"', '</svg>'),
  cloudsFar: innerOf('<svg class="clouds clouds--far"', '</svg>'),
  cloudsMid: innerOf('<svg class="clouds clouds--mid"', '</svg>'),
  branch: innerOf('<svg class="hero__branch"', '</svg>'),
};

writeFileSync(join(ROOT, 'proto/art.js'),
  `/* Generated by proto/build-art.mjs from index.html and css/tokens.css. Do not edit by hand. */\nwindow.PROTO_ART = ${JSON.stringify(art)};\n`);
console.log('proto/art.js', Object.entries(art).map(([k, v]) => `${k}:${typeof v === 'string' ? v.length : Object.keys(v).length}`).join(' '));
